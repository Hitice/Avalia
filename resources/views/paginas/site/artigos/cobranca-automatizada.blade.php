<p>
    Cobrar é necessário, mas cobrar mal custa caro: cliente constrangido não volta a comprar. A boa
    notícia é que a automação permite cobrar com mais regularidade e, ao mesmo tempo, com mais
    cuidado do que um processo manual.
</p>

<h2>A régua de cobrança</h2>
<p>
    A base de uma cobrança automatizada é a régua: a sequência de contatos que acontece antes e
    depois do vencimento. Um desenho comum inclui:
</p>
<ul>
    <li><strong>antes do vencimento:</strong> um lembrete amigável, com o boleto ou a chave Pix à mão;</li>
    <li><strong>no dia do vencimento:</strong> um aviso curto, sem tom de cobrança;</li>
    <li><strong>após o vencimento:</strong> contatos espaçados, com opções claras para regularizar;</li>
    <li><strong>casos prolongados:</strong> encaminhamento para uma pessoa da equipe negociar.</li>
</ul>
<p>
    Não existe régua única. Prazos, canais e tom devem refletir o perfil dos seus clientes e o tipo
    de relação que você quer manter.
</p>

<h2>Canal certo, tom certo</h2>
<p>
    E-mail e WhatsApp funcionam bem juntos: o e-mail formaliza, o WhatsApp é lido mais rápido.
    Mensagens curtas, com o valor, o vencimento e o meio de pagamento em destaque, resolvem a maior
    parte dos casos sem nenhuma intervenção humana.
</p>
<p>
    No WhatsApp, as mensagens iniciadas pela empresa precisam seguir as regras da plataforma, como
    modelos aprovados e consentimento do cliente para receber contatos. Planejar isso desde o
    início evita bloqueios.
</p>

<h2>Dentro da lei</h2>
<p>
    O Código de Defesa do Consumidor determina que, na cobrança de débitos, o consumidor não pode
    ser exposto a ridículo nem submetido a constrangimento ou ameaça. A LGPD, por sua vez, exige
    cuidado com os dados usados nos contatos. Uma régua bem desenhada respeita as duas coisas por
    padrão.
</p>

<h2>Baixa automática fecha o ciclo</h2>
<p>
    A automação só fica completa quando o pagamento é reconhecido sozinho. Conciliar o extrato
    bancário com os títulos em aberto interrompe a régua no momento certo e evita o erro mais
    incômodo de todos: cobrar quem já pagou.
</p>
